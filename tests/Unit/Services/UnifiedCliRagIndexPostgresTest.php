/** Dedicated database on an owned PostgreSQL cluster; no shared schema writes. */
class UnifiedCliRagIndexPostgresTest extends TestCase
{
    private PDO $admin;

    private string $database;

    private array $previousConfig;

    protected function setUp(): void
    {
        parent::setUp();
        $directory = getenv('PLOS_CLI_TEST_POSTGRES_DIRECTORY');
        if (! $directory) {
            $this->markTestSkipped('Run scripts/plos-cli/test-rag-postgres.py for isolated PostgreSQL coverage.');
        }
        $directory = realpath($directory);
        $this->assertNotFalse($directory);
        $this->assertStringStartsWith(sys_get_temp_dir().'/plos-cli-rag-test-', $directory);
        $this->admin = new PDO('pgsql:host='.$directory.';port=65431;dbname=postgres', 'plos_fixture', '', [PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION]);
        $identity = $this->admin->query("SELECT current_setting('data_directory') AS directory, inet_server_addr() AS address")->fetch(PDO::FETCH_ASSOC);
        $this->assertSame(realpath($directory.'/data'), realpath($identity['directory']));
        $this->assertNull($identity['address'], 'The fixture must use a private Unix socket.');
        $this->database = 'cli_rag_index_'.bin2hex(random_bytes(6));
        $this->admin->exec('CREATE DATABASE "'.$this->database.'"');
        $this->previousConfig = config('database.connections.pgsql_rag');
        DB::purge('pgsql_rag');
        config(['database.connections.pgsql_rag' => ['driver' => 'pgsql', 'host' => $directory, 'port' => 65431,
            'database' => $this->database, 'username' => 'plos_fixture', 'password' => '', 'charset' => 'utf8', 'prefix' => '', 'search_path' => 'public', 'sslmode' => 'disable']]);
        $db = DB::connection('pgsql_rag');
        $db->statement('CREATE EXTENSION vector');
        $dump = file_get_contents(database_path('schema/pgsql-schema.sql'));
        $this->assertSame(1, preg_match('/CREATE TABLE public\.rag_documents \(.*?;/s', $dump, $match));
        $db->unprepared($match[0]);
        // The original dump installs its ID sequence separately. Supply the
        // same generated-ID behavior within this dedicated fixture database.
        $db->statement('ALTER TABLE rag_documents ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY');
        Http::preventStrayRequests();
    }

    protected function tearDown(): void
    {
        if (isset($this->previousConfig)) {
            DB::purge('pgsql_rag');
            config(['database.connections.pgsql_rag' => $this->previousConfig]);
        }
        if (isset($this->database, $this->admin)) {
            $this->admin->exec('DROP DATABASE "'.$this->database.'"');
        }
        parent::tearDown();
    }

    private function embedding(): array
    {
        return ['success' => true, 'embedding' => array_fill(0, 768, 0.1), 'provider' => 'synthetic', 'model' => 'synthetic-embedding'];
    }

    private function graphSchema(): void
    {
        $dump = file_get_contents(database_path('schema/pgsql-schema.sql'));
        $db = DB::connection('pgsql_rag');
        foreach (['knowledge_graph', 'knowledge_graph_entities', 'knowledge_graph_edge_history', 'kg_quality_runs'] as $table) {
            $this->assertSame(1, preg_match('/CREATE TABLE public\.'.preg_quote($table, '/').' \(.*?;/s', $dump, $match));
            $db->unprepared($match[0]);
            $db->statement('ALTER TABLE '.$table.' ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY');
        }
    }

    public function test_graph_quality_reads_and_optional_persistence_report_actual_storage_outcomes(): void
    {
        $this->graphSchema();
        $db = DB::connection('pgsql_rag');
        $service = new KnowledgeGraphService(Mockery::mock(AIService::class));
        $result = $service->getQualityMetrics(['sample_size' => 7]);
        $this->assertSame(7, $result['sample_size']);
        $this->assertArrayNotHasKey('persisted', $result);
        $this->assertSame(0, $db->table('kg_quality_runs')->count());
        $saved = $service->getQualityMetrics(['sample_size' => 3, 'persist' => true]);
        $this->assertTrue($saved['persisted']);
        $row = $db->table('kg_quality_runs')->sole();
        $this->assertSame(3, $row->sample_size);
        $this->assertSame($saved['composite_score'], (float) $row->composite_score);
        $this->assertSame(0, $row->total_triples);
        // Exercise a real PostgreSQL insert failure without affecting a shared schema.
        $db->statement('ALTER TABLE kg_quality_runs ADD CONSTRAINT fixture_reject_save CHECK (sample_size <> 9)');
        $failed = $service->getQualityMetrics(['sample_size' => 9, 'persist' => true]);
        $this->assertFalse($failed['persisted']);
        $this->assertStringContainsString('fixture_reject_save', $failed['persistence_error']);
        $this->assertSame(1, $db->table('kg_quality_runs')->count());
    }

    public function test_graph_invalidation_retains_complete_reason_and_rolls_back_on_history_failure(): void
    {
        $this->graphSchema();
        $db = DB::connection('pgsql_rag');
        $triple = ['subject' => 'Synthetic José', 'subject_type' => 'person', 'predicate' => 'lives_in',
            'object' => 'Synthetic place', 'object_type' => 'location'];
        foreach ([17, 18, 19] as $id) {
            $db->table('knowledge_graph')->insert(['id' => $id] + $triple);
        }
        $reason = str_repeat("  Synthetic “correction”—José\r\n\t", 3000).' exact reason tail  ';
        $service = new KnowledgeGraphService(Mockery::mock(AIService::class));
        $this->assertTrue($service->invalidateTriple(17, ['reason' => $reason, 'superseded_by' => 18]));
        $row = $db->table('knowledge_graph')->where('id', 17)->sole();
        $this->assertNotNull($row->t_expired);
        $this->assertSame(18, $row->superseded_by);
        $history = $db->table('knowledge_graph_edge_history')->sole();
        $this->assertSame($reason, $history->reason);
        $this->assertSame('superseded', $history->action);
        $this->assertSame(18, $history->caused_by_triple_id);
        $this->assertSame('system', $history->actor);
        $this->assertSame(['t_expired' => null, 'superseded_by' => null], json_decode($history->old_values, true));
        $this->assertTrue($service->invalidateTriple(17, ['reason' => 'repeat']));
        $this->assertSame(1, $db->table('knowledge_graph_edge_history')->count());
        $this->assertFalse($service->invalidateTriple(999));
        $db->statement('ALTER TABLE knowledge_graph_edge_history ADD CONSTRAINT fixture_reject_history CHECK (triple_id <> 19)');
        $this->assertFalse($service->invalidateTriple(19, ['reason' => $reason, 'superseded_by' => 18]));
        $this->assertNull($db->table('knowledge_graph')->where('id', 19)->value('t_expired'));
        $this->assertNull($db->table('knowledge_graph')->where('id', 19)->value('superseded_by'));
        $this->assertSame(1, $db->table('knowledge_graph_edge_history')->count());
        $this->assertSame(0, $db->transactionLevel());
    }

    public function test_document_graph_build_sends_full_source_to_existing_pipeline_and_persists_its_graph(): void
    {
        $this->graphSchema();
        $db = DB::connection('pgsql_rag');
        $text = str_repeat("  Synthetic complete José source\r\n\t", 3000).' exact source tail  ';
        $title = '  Synthetic “source”—José  ';
        $snippet = str_repeat("  Synthetic verbatim evidence snippet\r\n\t", 2000).' exact snippet tail  ';
        $db->table('rag_documents')->insert(['id' => 17, 'document_type' => 'genealogy_research', 'content' => $text, 'title' => $title,
            'embedding' => json_encode($this->embedding()['embedding'])]);
        $spacy = Mockery::mock(SpacyNLPService::class);
        $spacy->shouldReceive('isAvailable')->once()->andReturn(false);
        $this->app->instance(SpacyNLPService::class, $spacy);
        $ai = Mockery::mock(AIService::class);
        $ai->shouldReceive('process')->once()->withArgs(function ($prompt, $options) use ($title, $text): bool {
            $this->assertStringContainsString("Title: {$title}\n\n{$text}", $prompt);
            $this->assertSame(1, substr_count($prompt, $text));
            $this->assertTrue($options['factual_mode']);

            return true;
        })->andReturn(['success' => true, 'response' => json_encode([
            'entities' => [['name' => 'Synthetic José', 'type' => 'person'], ['name' => 'Synthetic place', 'type' => 'location']],
            'relationships' => [['subject' => 'Synthetic José', 'subject_type' => 'person', 'predicate' => 'lives_in',
                'object' => 'Synthetic place', 'object_type' => 'location', 'confidence' => 0.95, 'source_snippet' => $snippet]],
        ], JSON_UNESCAPED_UNICODE | JSON_THROW_ON_ERROR)]);
        $result = (new KnowledgeGraphService($ai))->buildFromDocument(17);
        $this->assertTrue($result['success'], json_encode($result));
        $this->assertSame(2, $result['entities_extracted']);
        $this->assertSame(1, $result['triples_created']);
        $this->assertSame($title, $result['title']);
        $row = $db->table('knowledge_graph')->sole();
        $this->assertSame(17, $row->source_document_id);
        $this->assertSame($snippet, $row->extracted_from);
        $this->assertSame('Synthetic José', $row->subject);
        $this->assertSame('Synthetic place', $row->object);
        $this->assertSame(2, $db->table('knowledge_graph_entities')->count());
        $this->assertSame('created', $db->table('knowledge_graph_edge_history')->sole()->action);
        $source = $db->table('rag_documents')->where('id', 17)->sole();
        $this->assertNotNull($source->kg_extracted_at);
        $this->assertSame($text, $source->content);
        $this->assertSame($title, $source->title);
    }

    public function test_document_graph_model_failure_keeps_original_document_unmarked_and_creates_no_graph(): void
    {
        $this->graphSchema();
        $db = DB::connection('pgsql_rag');
        $text = str_repeat("  Synthetic original José evidence\r\n", 2000).' exact tail  ';
        $db->table('rag_documents')->insert(['id' => 17, 'document_type' => 'genealogy_research', 'content' => $text,
            'embedding' => json_encode($this->embedding()['embedding'])]);
        $db->table('rag_documents')->insert(['id' => 18, 'document_type' => 'genealogy_research', 'content' => 'short',
            'embedding' => json_encode($this->embedding()['embedding'])]);
        $spacy = Mockery::mock(SpacyNLPService::class);
        $spacy->shouldReceive('isAvailable')->once()->andReturn(false);
        $this->app->instance(SpacyNLPService::class, $spacy);
        $ai = Mockery::mock(AIService::class);
        $ai->shouldReceive('process')->once()->withArgs(fn ($prompt) => str_contains($prompt, $text))
            ->andReturn(['success' => false, 'error' => 'Synthetic selected model capacity failure']);
        $service = new KnowledgeGraphService($ai);
        $result = $service->buildFromDocument(17);
        $this->assertFalse($result['success']);
        $this->assertStringContainsString('Synthetic selected model capacity failure', $result['error']);
        $this->assertFalse($service->buildFromDocument(18)['success']);
        $this->assertFalse($service->buildFromDocument(999)['success']);
        $this->assertSame($text, $db->table('rag_documents')->where('id', 17)->value('content'));
        $this->assertNull($db->table('rag_documents')->where('id', 17)->value('kg_extracted_at'));
        $this->assertSame(0, $db->table('knowledge_graph')->count());
        $this->assertSame(0, $db->table('knowledge_graph_entities')->count());
        $this->assertSame(0, $db->table('knowledge_graph_edge_history')->count());
    }

    public function test_verbatim_index_round_trips_exact_text_and_title_through_real_pgvector_storage(): void
    {
        $text = str_repeat("  Synthetic José “source”—text…\u{00a0}\r\n\t\f", 2500).' exact tail  ';
        $title = '  Synthetic “title”—José…  ';
        $ai = Mockery::mock(AIService::class);
        $ai->shouldReceive('generateEmbedding')->once()->with($text, [])->andReturn($this->embedding());
        $service = new RAGService($ai, dedupService: new SemDeDupService($ai));
        $row = $service->indexDocument('genealogy_research', $text, $title, options: ['preserve_content' => true, 'skip_dedup' => true]);
        $this->assertGreaterThan(65535, strlen($text));
        $this->assertSame($text, $row->content);
        $this->assertSame($title, $row->title);
        $stored = DB::connection('pgsql_rag')->table('rag_documents')->where('id', $row->id)->first();
        $this->assertSame($text, $stored->content);
        $this->assertSame($title, $stored->title);
        $this->assertSame($text, $service->getFullDocuments([$row->id])[0]->content);
        $this->assertSame(768, json_decode($stored->metadata, true)['_plos_embedding']['dimensions']);
        $this->assertSame(1, DB::connection('pgsql_rag')->table('rag_documents')->count());
        // Existing callers retain normal sanitization unless they select preservation.
        $legacyText = '  Synthetic legacy “text”—José…  ';
        $ai->shouldReceive('generateEmbedding')->once()->with(trim($legacyText), [])->andReturn($this->embedding());
        $legacy = $service->indexDocument('document', $legacyText, $title, options: ['skip_dedup' => true]);
        $this->assertSame(DataSanitizer::cleanUtf8(trim($legacyText)), $legacy->content);
        $this->assertSame(DataSanitizer::cleanUtf8($title), $legacy->title);
    }

    public function test_unrepresentable_verbatim_input_is_rejected_before_embedding_or_storage(): void
    {
        $service = new RAGService(Mockery::mock(AIService::class));
        foreach ([["text\0tail", 'title'], ["bad\xff", 'title'], ['text', "title\0tail"], ['text', "title\xff"]] as [$text, $title]) {
            try {
                $service->indexDocument('document', $text, $title, options: ['preserve_content' => true, 'skip_dedup' => true]);
                $this->fail('Invalid text was silently altered or indexed.');
            } catch (\Exception $error) {
                $this->assertStringContainsString('valid UTF-8 text without NUL', $error->getMessage());
                $this->assertSame(0, DB::connection('pgsql_rag')->table('rag_documents')->count());
            }
        }
        try {
            $service->indexDocument('document', 'original text', 'title', sourceId: 17,
                options: ['preserve_content' => true, 'source_identity_upsert' => true]);
            $this->fail('Verbatim input without complete identity was admitted.');
        } catch (\Exception $error) {
            $this->assertStringContainsString('requires source_type and source_id', $error->getMessage());
            $this->assertSame(0, DB::connection('pgsql_rag')->table('rag_documents')->count());
        }
    }

    public function test_verbatim_identity_reindex_preserves_bytes_and_separates_distinct_sources(): void
    {
        $text = "  Exact José “source”—text…\u{00a0}\r\n\t tail  ";
        $title = '  Exact “title”—José…  ';
        $ai = Mockery::mock(AIService::class);
        $ai->shouldReceive('generateEmbedding')->twice()->with($text, [])->andReturn($this->embedding());
        $ai->shouldReceive('generateEmbedding')->once()->with($text)->andReturn($this->embedding());
        $service = new RAGService($ai, dedupService: new SemDeDupService($ai));
        $options = ['preserve_content' => true, 'source_identity_upsert' => true];
        $metadata = ['domain' => 'youtube', 'video_id' => 'abcdefghijk'];
        $first = $service->indexDocument('youtube_video', $text, $title, $metadata, sourceId: 797, sourceType: 'youtube_transcript', options: $options);
        $again = $service->indexDocument('youtube_video', $text, $title, $metadata, sourceId: 797, sourceType: 'youtube_transcript', options: $options);
        $other = $service->indexDocument('youtube_video', $text, $title, ['domain' => 'youtube', 'video_id' => 'lmnopqrstuv'],
            sourceId: 798, sourceType: 'youtube_transcript', options: $options);
        $this->assertSame($first->id, $again->id);
        $this->assertNotSame($first->id, $other->id);
        $this->assertSame(2, DB::connection('pgsql_rag')->table('rag_documents')->count());
        foreach ([$first, $again, $other] as $document) {
            $this->assertSame($text, $document->content);
            $this->assertSame($title, $document->title);
            $this->assertSame(hash('sha256', $text), $document->content_hash);
        }
    }

    public function test_legacy_unbound_youtube_identity_cannot_create_another_projection(): void
    {
        $db = DB::connection('pgsql_rag');
        $db->table('rag_documents')->insert(['document_type' => 'youtube_video', 'source_id' => '797', 'source_type' => null,
            'content' => 'Retained legacy source body', 'title' => 'Legacy title', 'embedding' => json_encode(array_fill(0, 768, 0.1))]);
        $ai = Mockery::mock(AIService::class);
        $ai->shouldNotReceive('generateEmbedding');
        try {
            (new RAGService($ai))->indexDocument('youtube_video', 'Different incoming source', metadata: ['domain' => 'youtube', 'video_id' => 'abcdefghijk'],
                sourceId: 797, sourceType: 'youtube_transcript', options: ['preserve_content' => true, 'source_identity_upsert' => true]);
            $this->fail('An unbound legacy source requires review.');
        } catch (\Exception $observed) {
            $this->assertStringContainsString('Legacy YouTube source identity requires review', $observed->getMessage());
        }
        $this->assertSame(1, $db->table('rag_documents')->count());
        $this->assertSame('Retained legacy source body', $db->table('rag_documents')->value('content'));
        $this->assertNull($db->table('rag_documents')->value('source_type'));
    }

    public function test_operator_selected_dedup_returns_only_byte_identical_content_without_mutating_a_match(): void
    {
        $text = '  Synthetic exact “text”—José…  ';
        $title = '  Synthetic exact title  ';
        $ai = Mockery::mock(AIService::class);
        $ai->shouldReceive('generateEmbedding')->once()->with($text, [])->andReturn($this->embedding());
        $service = new RAGService($ai, dedupService: new SemDeDupService($ai));
        $row = $service->indexDocument('document', $text, $title, options: ['preserve_content' => true, 'skip_dedup' => true]);
        $before = DB::connection('pgsql_rag')->table('rag_documents')->get()->toJson();
        $dedup = Mockery::mock(SemDeDupService::class);
        $dedup->shouldReceive('checkDuplicate')->times(4)->andReturn(['is_duplicate' => true, 'action' => 'update',
            'matched_document_id' => $row->id, 'content_hash' => $row->content_hash]);
        $deduplicating = new RAGService(Mockery::mock(AIService::class), dedupService: $dedup);
        $same = $deduplicating->indexDocument('document', $text, $title, options: ['preserve_content' => true, 'skip_dedup' => false]);
        $this->assertSame($row->id, $same->id);
        foreach ([['document', $text.' changed', $title], ['document', $text, $title.' changed'],
            ['genealogy_research', $text, $title]] as [$type, $changedText, $changedTitle]) {
            try {
                $deduplicating->indexDocument($type, $changedText, $changedTitle, options: ['preserve_content' => true, 'skip_dedup' => false]);
                $this->fail('A different source was returned as the indexed text.');
            } catch (\Exception $error) {
                $this->assertStringContainsString('deduplication match differs', $error->getMessage());
            }
        }
        $this->assertSame($before, DB::connection('pgsql_rag')->table('rag_documents')->get()->toJson());
    }
